"""Layer 1: authentication. Layer 2: rate limiting. Layer 3: replay defence.

Why these live together: all three answer the question *"should this request
be allowed to reach the router at all?"* and all three must run before any
application logic. Splitting them across modules would invite a caller to
wire up one and forget the others.

Threat model each piece addresses:

  auth.py      — an unauthenticated caller reading the audit ledger, or
                 invoking a policy decision. Tokens are stored as SHA-256
                 digests so a leaked config file does not leak credentials,
                 and comparison is constant-time so a response-time oracle
                 cannot be used to recover a token byte by byte.
  RateLimiter  — credential stuffing, ledger scraping, and denial of service
                 by request flood. A token bucket, per principal, refilled
                 continuously, so a burst is absorbed but sustained abuse
                 is refused with 429.
  ReplayGuard  — a captured request being replayed later. Every signed
                 request carries a timestamp and a single-use nonce; the
                 timestamp bounds how long a capture stays useful and the
                 nonce stops a capture being used twice inside that window.
"""

from __future__ import annotations

import hashlib
import hmac
import secrets
import threading
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml


class AuthError(Exception):
    """Authentication or request-integrity failure. Maps to HTTP 401/403."""


class RateLimited(Exception):
    """The caller exceeded its budget. Maps to HTTP 429."""


class ReplayDetected(Exception):
    """A nonce was reused or a timestamp fell outside the window."""


# --------------------------------------------------------------------------
# Layer 1 — authentication
# --------------------------------------------------------------------------


def hash_token(token: str) -> str:
    """Store the digest, never the credential itself.

    A plain SHA-256 is the right choice here rather than a password KDF: AXON
    tokens are high-entropy machine credentials generated by `axon token
    create`, not human-chosen passwords, so there is no dictionary to attack
    and a slow KDF would only tax every request.
    """
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


@dataclass
class Principal:
    """An authenticated caller: a human operator or a service."""

    name: str
    role: str = "viewer"
    scopes: set[str] = field(default_factory=set)
    enabled: bool = True

    def may(self, scope: str) -> bool:
        return "admin" in self.scopes or scope in self.scopes


@dataclass
class Token:
    name: str
    digest: str
    role: str = "viewer"
    scopes: set[str] = field(default_factory=set)
    enabled: bool = True

    @classmethod
    def issue(cls, name: str, role: str = "viewer", scopes: set[str] | None = None) -> tuple[Token, str]:
        """Create a token and return it alongside its plaintext, once.

        The plaintext is returned rather than stored, so it exists only in the
        caller's hand. `axon token create` prints it and never persists it.
        """
        plaintext = secrets.token_urlsafe(32)
        tok = cls(name=name, digest=hash_token(plaintext), role=role, scopes=scopes or set())
        return tok, plaintext


class Authenticator:
    """Verifies bearer tokens against a set of digests."""

    def __init__(self, tokens: dict[str, Token] | None = None, enabled: bool = True):
        self._tokens: dict[str, Token] = tokens or {}
        self.enabled = enabled

    @classmethod
    def from_yaml(cls, path: str | Path) -> Authenticator:
        data: dict[str, Any] = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
        tokens: dict[str, Token] = {}
        for name, spec in (data.get("tokens") or {}).items():
            spec = dict(spec or {})
            digest = str(spec.pop("digest", ""))
            if not digest:
                raise AuthError(f"token '{name}' has no digest")
            tokens[name] = Token(
                name=name,
                digest=digest,
                role=str(spec.pop("role", "viewer")),
                scopes=set(spec.pop("scopes", []) or []),
                enabled=bool(spec.pop("enabled", True)),
            )
        return cls(tokens, enabled=bool(data.get("enabled", True)))

    def add(self, token: Token) -> None:
        self._tokens[token.name] = token

    def authenticate(self, header: str | None) -> Principal:
        """Turn an Authorization header into a Principal, or refuse.

        Every failure path raises the same `AuthError` with the same message.
        Distinguishing "no such token" from "wrong token" would tell an
        attacker which half of their guess was right.
        """
        if not self.enabled:
            return Principal(name="anonymous", role="admin", scopes={"admin"})

        if not header:
            raise AuthError("missing Authorization header")
        parts = header.split(None, 1)
        if len(parts) != 2 or parts[0].lower() != "bearer":
            raise AuthError("Authorization must be 'Bearer <token>'")

        supplied = parts[1].strip()
        if not supplied:
            raise AuthError("empty bearer token")

        candidate = hash_token(supplied)
        matched: Token | None = None
        # Compare against every token with a constant-time comparison and do
        # not break early, so timing does not reveal which token matched.
        for token in self._tokens.values():
            if hmac.compare_digest(candidate, token.digest):
                matched = token
        if matched is None or not matched.enabled:
            raise AuthError("invalid credentials")

        return Principal(
            name=matched.name,
            role=matched.role,
            scopes=set(matched.scopes) | {matched.role},
        )

    def token_names(self) -> tuple[str, ...]:
        return tuple(sorted(self._tokens))


# --------------------------------------------------------------------------
# Layer 2 — rate limiting
# --------------------------------------------------------------------------


@dataclass
class _Bucket:
    tokens: float
    updated: float


class RateLimiter:
    """A token bucket per key, refilled continuously.

    A fixed window ("100 requests per minute") allows a caller to spend its
    whole budget in the last instant of one window and the first of the next,
    doubling the burst. A bucket cannot: the bucket is the ceiling, and it
    only ever refills at the stated rate.
    """

    def __init__(self, capacity: int = 60, refill_per_sec: float = 1.0):
        if capacity <= 0:
            raise ValueError("capacity must be positive")
        if refill_per_sec <= 0:
            raise ValueError("refill_per_sec must be positive")
        self.capacity = float(capacity)
        self.refill_per_sec = float(refill_per_sec)
        self._buckets: dict[str, _Bucket] = {}
        self._lock = threading.Lock()

    def check(self, key: str, cost: float = 1.0) -> float:
        """Consume `cost` tokens. Raise `RateLimited` when the bucket is dry.

        Returns the seconds the caller should wait, for the Retry-After header.
        """
        now = time.monotonic()
        with self._lock:
            bucket = self._buckets.get(key)
            if bucket is None:
                bucket = _Bucket(tokens=self.capacity, updated=now)
                self._buckets[key] = bucket

            elapsed = max(now - bucket.updated, 0.0)
            bucket.tokens = min(self.capacity, bucket.tokens + elapsed * self.refill_per_sec)
            bucket.updated = now

            if bucket.tokens < cost:
                deficit = cost - bucket.tokens
                raise RateLimited(f"retry after {deficit / self.refill_per_sec:.1f}s")
            bucket.tokens -= cost
            return 0.0

    def forget(self, key: str) -> None:
        """Drop a key's bucket. Used when a principal is revoked."""
        with self._lock:
            self._buckets.pop(key, None)

    def buckets(self) -> int:
        with self._lock:
            return len(self._buckets)


# --------------------------------------------------------------------------
# Layer 3 — replay defence
# --------------------------------------------------------------------------


class ReplayGuard:
    """Single-use nonces inside a bounded time window.

    A captured request is only useful while its timestamp is fresh, and only
    once. Both halves matter: without the window a nonce cache grows forever
    and an old capture stays valid; without the nonce a capture can be replayed
    as often as the attacker likes inside the window.
    """

    def __init__(self, window_seconds: int = 300, max_entries: int = 10_000):
        if window_seconds <= 0:
            raise ValueError("window_seconds must be positive")
        self.window = float(window_seconds)
        self.max_entries = max_entries
        self._seen: dict[str, float] = {}
        self._lock = threading.Lock()

    def _evict(self, now: float) -> None:
        stale = [n for n, t in self._seen.items() if now - t > self.window]
        for n in stale:
            del self._seen[n]

    def check(self, nonce: str, timestamp: float, now: float | None = None) -> None:
        """Raise `ReplayDetected` unless this nonce is fresh and unseen."""
        if not nonce:
            raise ReplayDetected("missing nonce")
        now = time.time() if now is None else now
        if abs(now - timestamp) > self.window:
            raise ReplayDetected(
                f"timestamp outside the ±{int(self.window)}s window "
                "(clock skew or a replayed capture)"
            )
        with self._lock:
            self._evict(now)
            if nonce in self._seen:
                raise ReplayDetected("nonce already used")
            if len(self._seen) >= self.max_entries:
                # Refuse rather than grow without bound. A full cache means an
                # unusual burst; dropping the oldest entry would quietly
                # reopen a replay hole, so we fail closed instead.
                raise ReplayDetected("nonce cache full")
            self._seen[nonce] = now

    def size(self) -> int:
        with self._lock:
            return len(self._seen)


# --------------------------------------------------------------------------
# Request signing — binds a request to a credential and its content
# --------------------------------------------------------------------------


def request_signature(
    secret: str,
    method: str,
    path: str,
    timestamp: float,
    nonce: str,
    body: bytes = b"",
) -> str:
    """HMAC over the parts of a request an attacker would want to change.

    The body digest is included so a captured request cannot be re-pointed at
    a different payload, and the path is included so it cannot be re-pointed
    at a different endpoint.
    """
    body_digest = hashlib.sha256(body).hexdigest()
    canonical = "\n".join([method.upper(), path, f"{timestamp:.0f}", nonce, body_digest])
    return hmac.new(secret.encode("utf-8"), canonical.encode("utf-8"), hashlib.sha256).hexdigest()


def verify_request_signature(
    secret: str,
    signature: str,
    method: str,
    path: str,
    timestamp: float,
    nonce: str,
    body: bytes = b"",
) -> bool:
    expected = request_signature(secret, method, path, timestamp, nonce, body)
    return hmac.compare_digest(expected, signature or "")
